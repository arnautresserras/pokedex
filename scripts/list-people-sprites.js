#!/usr/bin/env node
/**
 * Generate `src/play/peopleSprites.js` from the two Gen III trainer-sprite folders vendored
 * (by hand, not fetched) into `public/people/`:
 *
 *   public/people/gen3_back/            13 back-view walking sprites (Red, Leaf, Brendan...) —
 *                                        a story's stand-in for the child on the trail.
 *   public/people/gen3_trainer_sprites/ ~130 front-facing battle sprites (Gym Leaders, Elite
 *                                        Four, generic trainer classes, Team Rocket/Aqua/Magma) —
 *                                        no story uses these yet; this just makes them
 *                                        addressable by a stable id instead of a raw filename.
 *
 * Upstream filenames are inconsistent ("Spr FRLG Cooltrainer F.png", "E Brendan Back.png") and
 * contain spaces and accents, which makes them awkward and fragile to reference directly from
 * story content. This script slugifies each filename into a stable kebab-case id and writes a
 * manifest + two URL helpers, the same shape `fetch-type-icons.js` uses for the type pictograms.
 *
 * Re-run this whenever a file is added to either folder. Do not hand-edit the output.
 * Usage: node scripts/list-people-sprites.js
 */

import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const PEOPLE_DIR = path.join(ROOT, 'public', 'people')
const OUT_FILE = path.join(ROOT, 'src', 'play', 'peopleSprites.js')

const FOLDERS = {
  gen3_back: 'PROTAGONISTS',
  gen3_trainer_sprites: 'TRAINERS',
}

function slugify(filename) {
  return filename
    .replace(/\.png$/i, '')
    .replace(/^Spr\s+/, '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '') // strip accents (é → e)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
}

async function listEntries(folder) {
  const files = (await readdir(path.join(PEOPLE_DIR, folder)))
    .filter(f => f.toLowerCase().endsWith('.png'))
    .sort()

  const seen = new Set()
  return files.map(file => {
    let id = slugify(file)
    while (seen.has(id)) id += '-2'
    seen.add(id)
    return { id, file }
  })
}

async function main() {
  const entries = {}
  for (const folder of Object.keys(FOLDERS)) {
    entries[folder] = await listEntries(folder)
  }

  const render = list =>
    list.map(({ id, file }) => `  { id: '${id}', file: ${JSON.stringify(file)} },`).join('\n')

  const body = `/**
 * GENERATED by scripts/list-people-sprites.js from public/people/ — do not hand-edit.
 *
 * Two vendored Gen III sprite sets, addressed by a stable id instead of the raw (spaced,
 * inconsistently cased) upstream filename:
 *
 *   PROTAGONISTS  back-view walking sprites — a story's stand-in for the child on the trail.
 *   TRAINERS      front-facing battle sprites — not consumed by any story yet.
 */
const BASE = import.meta.env.BASE_URL

export const PROTAGONISTS = [
${render(entries.gen3_back)}
]

export const TRAINERS = [
${render(entries.gen3_trainer_sprites)}
]

function urlFor(list, dir, id) {
  const entry = list.find(e => e.id === id)
  return entry ? \`\${BASE}people/\${dir}/\${encodeURIComponent(entry.file)}\` : null
}

/** A protagonist back sprite by id (see PROTAGONISTS above), or null for an unknown id. */
export function protagonistBackUrl(id) {
  return urlFor(PROTAGONISTS, 'gen3_back', id)
}

/** A trainer battle sprite by id (see TRAINERS above), or null for an unknown id. */
export function trainerSpriteUrl(id) {
  return urlFor(TRAINERS, 'gen3_trainer_sprites', id)
}
`

  await writeFile(OUT_FILE, body)
  console.log(
    `wrote ${OUT_FILE.replace(ROOT + path.sep, '')} — ${entries.gen3_back.length} protagonists, ${entries.gen3_trainer_sprites.length} trainers`,
  )
}

main()
