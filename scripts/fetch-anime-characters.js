#!/usr/bin/env node
/**
 * Vendor a small, hand-curated set of original-series anime character artwork for the
 * "Aventures" mode (Kanto episodes EP001-EP010), into public/anime/, committed.
 *
 * Unlike fetch-play-assets.js (one predictable URL shape per cache entry) or
 * fetch-type-icons.js (one predictable URL per type), there is no predictable source URL per
 * character — each is a hand-picked Bulbagarden Archives file, chosen to match the original
 * series (1997-2002) look rather than a later era, so cast art stays consistent with the
 * Kanto-arc episodes being retold. See public/anime/CHARACTERS.LICENSE.txt for the licensing
 * basis (official copyrighted artwork, used under the Archives' own fair-use rationale, vendored
 * here only for this personal, unpublished, non-commercial family app).
 *
 * Idempotent: existing files are skipped unless --force is passed.
 * Usage: node scripts/fetch-anime-characters.js [--force]
 */

import { mkdir, writeFile, access } from 'node:fs/promises'
import path from 'node:path'
import sharp from 'sharp'

const ROOT = path.resolve(import.meta.dirname, '..')
const OUT_DIR = path.join(ROOT, 'public', 'anime')
const OUT_FILE = path.join(ROOT, 'src', 'play', 'animeCharacters.js')

const MAX_HEIGHT = 480
const FORCE = process.argv.includes('--force')
const DELAY_MS = 200

const CHARACTERS = [
  {
    id: 'ash',
    label: 'Ash Ketchum',
    url: 'https://archives.bulbagarden.net/media/upload/4/4e/Ash_OS_1.png',
    source: 'https://archives.bulbagarden.net/wiki/File:Ash_OS_1.png',
  },
  {
    id: 'misty',
    label: 'Misty',
    url: 'https://archives.bulbagarden.net/media/upload/4/4f/Misty_OS_2.png',
    source: 'https://archives.bulbagarden.net/wiki/File:Misty_OS_2.png',
  },
  {
    id: 'brock',
    label: 'Brock',
    url: 'https://archives.bulbagarden.net/media/upload/b/bb/Brock_OS.png',
    source: 'https://archives.bulbagarden.net/wiki/File:Brock_OS.png',
  },
  {
    id: 'oak',
    label: 'Professor Oak',
    url: 'https://archives.bulbagarden.net/media/upload/f/f0/Professor_Oak_OS_anime.png',
    source: 'https://archives.bulbagarden.net/wiki/File:Professor_Oak_OS_anime.png',
  },
  {
    id: 'team-rocket',
    label: 'Team Rocket (Jessie, James, Meowth)',
    url: 'https://archives.bulbagarden.net/media/upload/b/b0/Team_Rocket_trio_OS.png',
    source: 'https://archives.bulbagarden.net/wiki/File:Team_Rocket_trio_OS.png',
  },
]

const sleep = ms => new Promise(r => setTimeout(r, ms))
const exists = async p => access(p).then(() => true, () => false)

async function download(url, attempt = 1) {
  try {
    const res = await fetch(url)
    if (!res.ok) throw new Error(`HTTP ${res.status}`)
    return Buffer.from(await res.arrayBuffer())
  } catch (err) {
    if (attempt >= 4) throw err
    await sleep(500 * attempt)
    return download(url, attempt + 1)
  }
}

async function main() {
  await mkdir(OUT_DIR, { recursive: true })

  let fetched = 0
  let skipped = 0
  const failures = []

  for (const character of CHARACTERS) {
    const outPath = path.join(OUT_DIR, `${character.id}.webp`)
    if (!FORCE && (await exists(outPath))) {
      skipped++
      continue
    }
    try {
      const raw = await download(character.url)
      const webp = await sharp(raw)
        .resize({ height: MAX_HEIGHT, fit: 'inside', withoutEnlargement: true })
        .webp({ quality: 90 })
        .toBuffer()
      await writeFile(outPath, webp)
      fetched++
      console.log(`  ${character.id}.webp`)
      await sleep(DELAY_MS)
    } catch (err) {
      failures.push({ id: character.id, message: err.message })
    }
  }

  console.log(`fetched ${fetched}, skipped ${skipped}, failed ${failures.length}`)
  if (failures.length) {
    for (const f of failures) console.error(`  ${f.id}: ${f.message}`)
    process.exitCode = 1
    return
  }

  const entries = CHARACTERS.map(c => `  { id: '${c.id}', label: ${JSON.stringify(c.label)} },`).join('\n')
  const body = `/**
 * GENERATED by scripts/fetch-anime-characters.js — do not hand-edit.
 * Vendored original-series anime character art for "Aventures" mode. See
 * public/anime/CHARACTERS.LICENSE.txt for source/licensing.
 */
const BASE = import.meta.env.BASE_URL

export const CHARACTERS = [
${entries}
]

/** A vendored anime character portrait by id (see CHARACTERS above), or null for an unknown id. */
export function characterUrl(id) {
  return CHARACTERS.some(c => c.id === id) ? \`\${BASE}anime/\${id}.webp\` : null
}
`
  await writeFile(OUT_FILE, body)
  console.log(`wrote ${OUT_FILE.replace(ROOT + path.sep, '')}`)

  const license = `The character portraits in public/anime/ are official Pokémon animation artwork
(original series era), sourced from Bulbagarden Archives and used there under their own fair-use
rationale for encyclopedic/reference use (see https://archives.bulbagarden.net/wiki/Bulbapedia:Copyrights).
They remain the copyright of their respective owners (The Pokémon Company / Nintendo / Game Freak /
OLM). Vendored here only for this personal, unpublished, non-commercial family app — not for
redistribution.

Sources:
${CHARACTERS.map(c => `  ${c.id} (${c.label}): ${c.source}`).join('\n')}
`
  await writeFile(path.join(OUT_DIR, 'CHARACTERS.LICENSE.txt'), license)
}

main()
